/**
 * PDF Export Service using PDFKit
 *
 * IMPORTANT: Generated PDFs are summary reports only.
 * They are NOT official university marksheets or transcripts.
 * This disclaimer is included on every generated PDF.
 */

const PDFDocument = require('pdfkit');
const fs = require('fs');
const path = require('path');
const archiver = require('archiver');

const DISCLAIMER = 'DISCLAIMER: This is a summary report generated by RGPV Smart Bulk Result Manager for reference purposes only. It is NOT an official university document, marksheet, or transcript. For official records, please refer to the RGPV official portal at result.rgpv.ac.in';

function generateStudentPDF(student, outputPath) {
      return new Promise((resolve, reject) => {
            const doc = new PDFDocument({ margin: 50, size: 'A4' });
            const stream = fs.createWriteStream(outputPath);

            doc.pipe(stream);

            // Header
            doc.rect(50, 50, doc.page.width - 100, 60).fill('#1E3A5F');
            doc.fillColor('white').fontSize(18).font('Helvetica-Bold')
                  .text('RGPV Smart Bulk Result Manager', 50, 65, { align: 'center', width: doc.page.width - 100 });
            doc.fontSize(11).font('Helvetica')
                  .text('Student Result Summary (Reference Only)', 50, 88, { align: 'center', width: doc.page.width - 100 });

            doc.fillColor('black').moveDown(2);

            // Disclaimer box
            doc.rect(50, doc.y, doc.page.width - 100, 50).fill('#FFF3CD').stroke('#FFC107');
            doc.fillColor('#856404').fontSize(8).font('Helvetica')
                  .text(DISCLAIMER, 60, doc.y + 5, { width: doc.page.width - 120 });
            doc.fillColor('black').moveDown(2);

            const y = doc.y + 10;

            // Student info
            doc.fontSize(13).font('Helvetica-Bold').text('Student Information', 50, y);
            doc.moveTo(50, doc.y + 2).lineTo(doc.page.width - 50, doc.y + 2).stroke('#1E3A5F');
            doc.moveDown(0.5);

            const infoItems = [
                  ['Enrollment Number', student.enrollmentNumber],
                  ['Student Name', student.studentName || 'N/A'],
                  ['College Code', student.collegeCode || 'N/A'],
                  ['Branch', student.branch || 'N/A'],
                  ['Semester', student.semester || 'N/A'],
                  ['Examination', `${student.examinationSession || ''} ${student.examinationYear || ''}`],
            ];

            infoItems.forEach(([label, value]) => {
                  doc.fontSize(10).font('Helvetica-Bold').text(`${label}: `, { continued: true })
                        .font('Helvetica').text(String(value));
            });

            doc.moveDown(1);

            // Subjects table
            if (student.subjects && student.subjects.length > 0) {
                  doc.fontSize(13).font('Helvetica-Bold').text('Subject Details');
                  doc.moveTo(50, doc.y + 2).lineTo(doc.page.width - 50, doc.y + 2).stroke('#1E3A5F');
                  doc.moveDown(0.5);

                  const colWidths = [60, 150, 55, 55, 55, 55, 50, 40];
                  const headers = ['Code', 'Subject Name', 'Internal', 'External', 'Practical', 'Total', 'Credits', 'Grade'];
                  const startX = 50;

                  // Header row
                  doc.rect(startX, doc.y, doc.page.width - 100, 20).fill('#1E3A5F');
                  let cx = startX + 5;
                  headers.forEach((h, i) => {
                        doc.fillColor('white').fontSize(8).font('Helvetica-Bold').text(h, cx, doc.y - 15, { width: colWidths[i] });
                        cx += colWidths[i];
                  });
                  doc.fillColor('black').moveDown(0.3);

                  student.subjects.forEach((sub, idx) => {
                        const rowY = doc.y;
                        if (idx % 2 === 0) {
                              doc.rect(startX, rowY, doc.page.width - 100, 18).fill('#F5F5F5');
                        }
                        const vals = [
                              sub.subjectCode || '',
                              sub.subjectName || '',
                              sub.internalMarks != null ? sub.internalMarks : '-',
                              sub.externalMarks != null ? sub.externalMarks : '-',
                              sub.practicalMarks != null ? sub.practicalMarks : '-',
                              sub.totalMarks != null ? sub.totalMarks : '-',
                              sub.credits != null ? sub.credits : '-',
                              sub.grade || '-',
                        ];
                        cx = startX + 5;
                        vals.forEach((v, i) => {
                              doc.fillColor('black').fontSize(8).font('Helvetica').text(String(v), cx, rowY + 4, { width: colWidths[i] });
                              cx += colWidths[i];
                        });
                        doc.moveDown(0.9);
                  });
            }

            doc.moveDown(1);

            // Summary
            doc.fontSize(13).font('Helvetica-Bold').text('Academic Summary');
            doc.moveTo(50, doc.y + 2).lineTo(doc.page.width - 50, doc.y + 2).stroke('#1E3A5F');
            doc.moveDown(0.5);

            const summaryItems = [
                  ['SGPA', student.sgpa != null ? student.sgpa : 'N/A'],
                  ['CGPA', student.cgpa != null ? student.cgpa : 'N/A'],
                  ['Total Credits', student.totalCredits != null ? student.totalCredits : 'N/A'],
                  ['Backlogs', student.backlogs != null ? student.backlogs : 0],
                  ['Result Status', student.resultStatus || 'N/A'],
            ];

            summaryItems.forEach(([label, value]) => {
                  doc.fontSize(11).font('Helvetica-Bold').text(`${label}: `, { continued: true })
                        .font('Helvetica').text(String(value));
            });

            // Footer
            const footerY = doc.page.height - 80;
            doc.fontSize(8).fillColor('#666').text(
                  `Generated: ${new Date().toLocaleString()} | Source: ${student.source || 'N/A'} | For official records visit result.rgpv.ac.in`,
                  50, footerY, { align: 'center', width: doc.page.width - 100 }
            );

            doc.end();

            stream.on('finish', () => resolve(outputPath));
            stream.on('error', reject);
      });
}

async function generateZipArchive(filePaths, zipPath) {
      return new Promise((resolve, reject) => {
            const output = fs.createWriteStream(zipPath);
            const archive = archiver('zip', { zlib: { level: 9 } });

            output.on('close', () => resolve(zipPath));
            archive.on('error', reject);
            archive.pipe(output);

            filePaths.forEach((fp) => {
                  if (fs.existsSync(fp)) {
                        archive.file(fp, { name: path.basename(fp) });
                  }
            });

            archive.finalize();
      });
}

module.exports = { generateStudentPDF, generateZipArchive };
